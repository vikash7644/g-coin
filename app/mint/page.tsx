import { redirect } from 'next/navigation';

import { CoinCanvas } from '@/components/CoinCanvas';
import { NavBar } from '@/components/NavBar';
import { getCurrentUser } from '@/lib/auth';
import { prisma } from '@/lib/db';

export default async function MintPage() {
  const user = await getCurrentUser();
  if (!user) redirect('/login');

  const eligibleSubmissions = await prisma.submission.findMany({
    where: {
      userId: user.id,
      status: 'APPROVED',
      mintToken: { not: null },
      mintTokenExpiresAt: { gt: new Date() },
    },
  });

  return (
    <main className="min-h-screen bg-slate-950 text-white">
      <NavBar />
      <div className="mx-auto max-w-6xl px-6 py-12">
        <div className="mb-8">
          <p className="text-sm uppercase tracking-[0.2em] text-yellow-300">Mint your G-COIN</p>
          <h1 className="mt-2 text-4xl font-black">Build-to-mint</h1>
        </div>

        {!eligibleSubmissions.length ? (
          <div className="rounded-2xl border border-white/10 bg-slate-900 p-8 text-slate-300">
            No valid mint token found. Your approved submission must be approved by admin and still within the 24-hour mint window.
          </div>
        ) : (
          <div className="grid gap-8 lg:grid-cols-[1.2fr_0.8fr]">
            <div className="rounded-3xl border border-white/10 bg-slate-900 p-8">
              <div className="mb-6 flex justify-center">
                <CoinCanvas />
              </div>

              {eligibleSubmissions.map((submission) => (
                <form key={submission.id} action="/api/mint" method="POST" className="space-y-5">
                  <input type="hidden" name="submissionId" value={submission.id} />

                  <div>
                    <label className="mb-2 block text-sm text-slate-300">Project title</label>
                    <input name="projectTitle" defaultValue={submission.projectTitle} className="w-full rounded-xl border border-white/10 bg-slate-950 px-4 py-3 text-white outline-none focus:border-yellow-400" readOnly />
                  </div>

                  <div>
                    <label className="mb-2 block text-sm text-slate-300">Description</label>
                    <textarea name="description" defaultValue={submission.description} rows={4} className="w-full rounded-xl border border-white/10 bg-slate-950 px-4 py-3 text-white outline-none focus:border-yellow-400" readOnly />
                  </div>

                  <div>
                    <label className="mb-2 block text-sm text-slate-300">Tech stack used</label>
                    <input name="techStackUsed" defaultValue={submission.techStackUsed} className="w-full rounded-xl border border-white/10 bg-slate-950 px-4 py-3 text-white outline-none focus:border-yellow-400" readOnly />
                  </div>

                  <div className="rounded-xl border border-yellow-400/30 bg-yellow-500/10 p-4 text-sm text-yellow-200">
                    Auto-assigned edition: 001/100 with rarity logic generated by system.
                  </div>

                  <button type="submit" className="w-full rounded-xl bg-yellow-400 px-4 py-3 font-semibold text-slate-900 hover:bg-yellow-300">
                    Mint G-COIN asset
                  </button>
                </form>
              ))}
            </div>

            <div className="rounded-3xl border border-white/10 bg-slate-900 p-8">
              <h2 className="text-2xl font-bold">Mint rules</h2>
              <ul className="mt-6 space-y-4 text-slate-300">
                <li>• Only approved submissions with an active mint token qualify.</li>
                <li>• The first 10 minted entries are LEGENDARY.</li>
                <li>• The next 20 are EPIC.</li>
                <li>• Rest are RARE.</li>
                <li>• Asset value is based on supply, proof-of-work, and market demand.</li>
              </ul>
            </div>
          </div>
        )}
      </div>
    </main>
  );
}
